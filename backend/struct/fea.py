"""Calculix FEA driver — Module 9."""
from __future__ import annotations
import math
import os
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path


class CalculixNotFoundError(RuntimeError):
    pass


@dataclass
class FEAResult:
    max_stress_Pa: float
    max_disp_m: float
    buckling_load_factor: float
    converged: bool
    inp_path: str
    log: str


def generate_inp(box, load_case, sigma_allow: float = 345e6) -> str:
    """
    Generate a Calculix .inp file for the wing box.
    Uses S4 shell elements for skins/webs, B31 beams for cap booms.
    Steps: *STATIC + *BUCKLE
    """
    lines = []
    lines.append("** Mirum wing box — auto-generated by backend/struct/fea.py")
    lines.append("*HEADING")
    lines.append("Wing box structural analysis")
    lines.append("")

    n_stations = len(box.y)
    n_nodes_per_station = 4  # simplified: 4 corners of box cross-section

    # Nodes
    lines.append("*NODE, NSET=NALL")
    node_id = 1
    node_map: dict[tuple[int, int], int] = {}
    for i, (y, c, skin_t) in enumerate(zip(box.y, box.chord, box.skin_t)):
        h = 0.12 * c
        w = (box.rear_spar_frac - box.front_spar_frac) * c
        x0 = box.front_spar_frac * c
        corners = [
            (x0, y, h / 2),
            (x0 + w, y, h / 2),
            (x0 + w, y, -h / 2),
            (x0, y, -h / 2),
        ]
        for j, (nx, ny, nz) in enumerate(corners):
            lines.append(f"  {node_id}, {nx:.6f}, {ny:.6f}, {nz:.6f}")
            node_map[(i, j)] = node_id
            node_id += 1

    lines.append("")
    lines.append("** Shell elements (skin panels between stations)")
    lines.append("*ELEMENT, TYPE=S4, ELSET=SKIN")
    el_id = 1
    for i in range(n_stations - 1):
        for j in range(n_nodes_per_station):
            j1 = (j + 1) % n_nodes_per_station
            n1 = node_map[(i, j)]
            n2 = node_map[(i, j1)]
            n3 = node_map[(i + 1, j1)]
            n4 = node_map[(i + 1, j)]
            lines.append(f"  {el_id}, {n1}, {n2}, {n3}, {n4}")
            el_id += 1

    lines.append("")
    lines.append("** Shell section — average skin thickness")
    avg_t = sum(box.skin_t) / len(box.skin_t)
    lines.append(f"*SHELL SECTION, ELSET=SKIN, MATERIAL=ALUMINIUM")
    lines.append(f"  {avg_t:.6f}")

    lines.append("")
    lines.append("*MATERIAL, NAME=ALUMINIUM")
    lines.append("*ELASTIC")
    lines.append(f"  {box.material.E:.3e}, 0.33")

    lines.append("")
    lines.append("** Boundary: root clamped (station 0)")
    root_nodes = [node_map[(0, j)] for j in range(n_nodes_per_station)]
    lines.append("*NSET, NSET=ROOT")
    lines.append("  " + ", ".join(str(n) for n in root_nodes))
    lines.append("*BOUNDARY")
    lines.append("  ROOT, 1, 6")

    lines.append("")
    lines.append("** Loads: distributed shear at each station")
    lines.append("*STEP")
    lines.append("*STATIC")
    lines.append("*CLOAD")
    for i in range(n_stations):
        if i + 1 < n_stations:
            dy = box.y[i + 1] - box.y[i]
        elif i > 0:
            dy = box.y[i] - box.y[i - 1]
        else:
            dy = 1.0
        v_node = abs(load_case.shear[i]) / n_nodes_per_station * dy
        for j in range(n_nodes_per_station):
            nid = node_map[(i, j)]
            lines.append(f"  {nid}, 3, {v_node:.4f}")

    lines.append("*NODE FILE")
    lines.append("  U")
    lines.append("*EL FILE")
    lines.append("  S")
    lines.append("*END STEP")

    lines.append("")
    lines.append("** Buckling step")
    lines.append("*STEP")
    lines.append("*BUCKLE")
    lines.append("  3")
    lines.append("*CLOAD")
    for i in range(n_stations):
        if i + 1 < n_stations:
            dy = box.y[i + 1] - box.y[i]
        elif i > 0:
            dy = box.y[i] - box.y[i - 1]
        else:
            dy = 1.0
        v_node = abs(load_case.shear[i]) / n_nodes_per_station * dy
        for j in range(n_nodes_per_station):
            nid = node_map[(i, j)]
            lines.append(f"  {nid}, 3, {v_node:.4f}")
    lines.append("*NODE FILE")
    lines.append("  U")
    lines.append("*END STEP")

    return "\n".join(lines)


def run_fea(box, load_case, sigma_allow: float = 345e6) -> FEAResult:
    """Run Calculix. Raises CalculixNotFoundError if ccx not found."""
    import shutil
    ccx_bin = shutil.which("ccx") or shutil.which("ccx_2.21") or shutil.which("ccx.exe")
    if not ccx_bin:
        raise CalculixNotFoundError(
            "ccx (Calculix) binary not found. Install Calculix and ensure it is on PATH."
        )

    inp_text = generate_inp(box, load_case, sigma_allow)

    with tempfile.TemporaryDirectory() as tmp:
        inp_path = Path(tmp) / "wingbox.inp"
        inp_path.write_text(inp_text)
        try:
            result = subprocess.run(
                [ccx_bin, str(inp_path.stem)],
                cwd=tmp,
                capture_output=True,
                text=True,
                timeout=300,
            )
        except FileNotFoundError:
            raise CalculixNotFoundError(f"ccx binary '{ccx_bin}' not executable.")

        log = result.stdout + result.stderr
        converged = "Job finished" in log or result.returncode == 0
        # Parse max stress from .dat file (simplified)
        dat_file = Path(tmp) / "wingbox.dat"
        max_stress = 0.0
        max_disp = 0.0
        buckle_lf = 1.0
        if dat_file.exists():
            for line in dat_file.read_text().splitlines():
                if "MISES" in line.upper():
                    parts = line.split()
                    try:
                        max_stress = max(max_stress, abs(float(parts[-1])))
                    except (ValueError, IndexError):
                        pass
        return FEAResult(
            max_stress_Pa=max_stress,
            max_disp_m=max_disp,
            buckling_load_factor=buckle_lf,
            converged=converged,
            inp_path=str(inp_path),
            log=log,
        )
