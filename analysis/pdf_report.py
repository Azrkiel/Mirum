"""
analysis/pdf_report.py — XFOIL PDF export (PDF-02).
====================================================

Generates a multi-page PDF report from a completed XFOIL polar run.

Usage
-----
    from analysis.pdf_report import generate_xfoil_pdf

    pdf_bytes = generate_xfoil_pdf(
        polar=polar_report.model_dump(),
        cl_alpha_b64=cl_b64,
        cd_alpha_b64=cd_b64,
        cp_dist_b64=cp_b64,   # may be None
    )
    # pdf_bytes is raw PDF bytes — stream directly or write to disk.

PDF structure
-------------
  Page 1  Cover: dark header bar, large NACA code, metadata row, generated timestamp
  Page 2  Summary table (Cl_max, stall α, max L/D, α@maxLD, Cd_min, converged pts)
          + Cl vs α chart
  Page 3  Cd vs α chart + Cp distribution (skipped when cp_dist_b64 is None)
  Page 4+ Full polar data table, paginated at 40 rows/page
  Footer  Page number + "Generated by Mirum · mirum.ai" on every page
"""

from __future__ import annotations

import base64
import math
import os
import tempfile
from datetime import datetime
from typing import Optional

from fpdf import FPDF


# ---------------------------------------------------------------------------
# Style constants (dark palette matching the matplotlib charts)
# ---------------------------------------------------------------------------

_DARK_BG   = (14, 17, 23)      # #0e1117 — Streamlit dark
_HEADER_BG = (22, 27, 34)      # slightly lighter for section headers
_ACCENT    = (79, 142, 247)    # #4f8ef7 — blue
_STALL     = (255, 75, 75)     # #ff4b4b — red
_TEXT_MAIN = (200, 204, 214)   # #c8ccd6 — body text
_TEXT_DIM  = (140, 145, 160)   # dimmer text for subtitles/footers
_WHITE     = (255, 255, 255)
_ROW_ALT   = (24, 28, 38)      # alternate row shading

_PAGE_W = 210   # A4 mm
_MARGIN = 14    # left/right margin mm
_COL_W  = _PAGE_W - 2 * _MARGIN  # usable width


# ---------------------------------------------------------------------------
# MirumPDF — subclass with auto-footer
# ---------------------------------------------------------------------------

class _MirumPDF(FPDF):
    """FPDF subclass that renders a branded footer on every page."""

    def footer(self) -> None:
        self.set_y(-12)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(*_TEXT_DIM)
        # Page number (left)
        self.cell(_COL_W // 2, 5, f"Page {self.page_no()}", align="L")
        # Branding (right)
        self.cell(_COL_W // 2, 5, "Generated by Mirum · mirum.ai", align="R")


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _set_fill(pdf: _MirumPDF, rgb: tuple[int, int, int]) -> None:
    pdf.set_fill_color(*rgb)


def _set_text(pdf: _MirumPDF, rgb: tuple[int, int, int]) -> None:
    pdf.set_text_color(*rgb)


def _embed_png(pdf: _MirumPDF, b64_png: str, tmpdir: str, label: str) -> None:
    """Decode a base64 PNG, save to a temp file, and embed it in the PDF."""
    img_bytes = base64.b64decode(b64_png)
    img_path = os.path.join(tmpdir, f"{label}.png")
    with open(img_path, "wb") as fh:
        fh.write(img_bytes)
    # Scale to full usable width, preserving aspect ratio (FPDF handles height=0)
    pdf.image(img_path, x=_MARGIN, w=_COL_W, h=0)


def _safe_float(value, default: float = 0.0) -> float:
    """Return value as float, or default if None / NaN / Inf."""
    if value is None:
        return default
    try:
        v = float(value)
        return v if math.isfinite(v) else default
    except (TypeError, ValueError):
        return default


def _compute_summary(polar: dict) -> dict:
    """Extract key performance metrics from a PolarReport dict."""
    Cl_max: Optional[float] = polar.get("Cl_max")
    stall_alpha: Optional[float] = polar.get("stall_alpha")
    alpha_list = polar.get("alpha") or []
    Cd_list = polar.get("Cd") or []
    L_D_list = polar.get("L_D") or []
    converged = polar.get("converged_count", 0)
    total = len(alpha_list)

    # Max L/D and the alpha at which it occurs
    max_LD: Optional[float] = None
    alpha_at_max_LD: Optional[float] = None
    if L_D_list and alpha_list:
        valid = [
            (a, ld)
            for a, ld in zip(alpha_list, L_D_list)
            if ld is not None and math.isfinite(float(ld))
        ]
        if valid:
            alpha_at_max_LD, max_LD = max(valid, key=lambda p: p[1])

    # Cd_min — minimum finite Cd value
    Cd_min: Optional[float] = None
    valid_cd = [c for c in Cd_list if c is not None and math.isfinite(float(c)) and float(c) > 0]
    if valid_cd:
        Cd_min = min(float(c) for c in valid_cd)

    return {
        "Cl_max": Cl_max,
        "stall_alpha": stall_alpha,
        "max_LD": max_LD,
        "alpha_at_max_LD": alpha_at_max_LD,
        "Cd_min": Cd_min,
        "converged": converged,
        "total": total,
    }


# ---------------------------------------------------------------------------
# Page builders
# ---------------------------------------------------------------------------

def _build_cover(pdf: _MirumPDF, polar: dict) -> None:
    """Page 1: branded cover with dark background."""
    pdf.add_page()

    # Full-page dark background
    _set_fill(pdf, _DARK_BG)
    pdf.rect(0, 0, 210, 297, "F")

    # Header bar
    _set_fill(pdf, _HEADER_BG)
    pdf.rect(0, 0, 210, 52, "F")

    # Product name
    pdf.set_y(12)
    pdf.set_font("Helvetica", "B", 22)
    _set_text(pdf, _ACCENT)
    pdf.cell(210, 10, "MIRUM", align="C", ln=True)

    pdf.set_font("Helvetica", "", 11)
    _set_text(pdf, _TEXT_MAIN)
    pdf.cell(210, 7, "Aerodynamic Analysis Report", align="C", ln=True)

    # Large NACA code
    pdf.set_y(68)
    naca = polar.get("naca_code", "????")
    pdf.set_font("Helvetica", "B", 48)
    _set_text(pdf, _WHITE)
    pdf.cell(210, 18, f"NACA {naca}", align="C", ln=True)

    # Divider
    pdf.set_y(92)
    _set_fill(pdf, _ACCENT)
    pdf.rect(_MARGIN, pdf.get_y(), _COL_W, 1.2, "F")
    pdf.ln(6)

    # Metadata table (2-column grid)
    reynolds = _safe_float(polar.get("reynolds"))
    mach = _safe_float(polar.get("mach"))
    n_crit = _safe_float(polar.get("n_crit"), 9.0)
    chord_mm = _safe_float(polar.get("chord_mm"))

    meta_items = [
        ("Reynolds number", f"{reynolds:,.0f}"),
        ("Mach number", f"{mach:.3f}"),
        ("Ncrit (transition)", f"{n_crit:.1f}"),
        ("Chord", f"{chord_mm:.1f} mm"),
        ("Generated", datetime.now().strftime("%Y-%m-%d  %H:%M UTC")),
        ("Airfoil family", "NACA 4-digit"),
    ]

    col_w = _COL_W / 2
    pdf.set_font("Helvetica", "", 9.5)
    _set_text(pdf, _TEXT_DIM)

    for i, (label, value) in enumerate(meta_items):
        x = _MARGIN + (i % 2) * col_w
        pdf.set_x(x)
        if i % 2 == 0 and i > 0:
            pdf.ln(0)
        pdf.set_font("Helvetica", "", 8)
        _set_text(pdf, _TEXT_DIM)
        pdf.cell(col_w * 0.45, 7, label, ln=False)
        pdf.set_font("Helvetica", "B", 8.5)
        _set_text(pdf, _TEXT_MAIN)
        pdf.cell(col_w * 0.55, 7, value, ln=(1 if i % 2 == 1 else 0))
    pdf.ln(2)

    # Footer note
    pdf.set_y(-35)
    pdf.set_font("Helvetica", "I", 7.5)
    _set_text(pdf, _TEXT_DIM)
    pdf.cell(210, 5, "Analysis performed with XFOIL — www.mit.edu/drela/Public/web/xfoil/", align="C")


def _build_summary_table(pdf: _MirumPDF, summary: dict) -> None:
    """Section: performance summary table."""
    pdf.set_font("Helvetica", "B", 11)
    _set_text(pdf, _ACCENT)
    pdf.cell(_COL_W, 7, "Performance Summary", ln=True)
    pdf.ln(2)

    rows = [
        ("Cl_max",             f"{summary['Cl_max']:.4f}"       if summary["Cl_max"]         is not None else "n/a"),
        ("Stall alpha",        f"{summary['stall_alpha']:.1f}°"  if summary["stall_alpha"]    is not None else "n/a"),
        ("Max L/D",            f"{summary['max_LD']:.2f}"        if summary["max_LD"]         is not None else "n/a"),
        ("Alpha @ max L/D",    f"{summary['alpha_at_max_LD']:.1f}°" if summary["alpha_at_max_LD"] is not None else "n/a"),
        ("Cd_min",             f"{summary['Cd_min']:.5f}"        if summary["Cd_min"]         is not None else "n/a"),
        ("Converged points",   f"{summary['converged']} / {summary['total']}"),
    ]

    col_label = _COL_W * 0.55
    col_value = _COL_W * 0.45
    row_h = 7

    for i, (label, value) in enumerate(rows):
        fill = _ROW_ALT if i % 2 == 0 else _DARK_BG
        _set_fill(pdf, fill)
        _set_text(pdf, _TEXT_DIM)
        pdf.set_font("Helvetica", "", 9)
        pdf.set_x(_MARGIN)
        pdf.cell(col_label, row_h, f"  {label}", fill=True, ln=False)
        _set_text(pdf, _TEXT_MAIN)
        pdf.set_font("Helvetica", "B", 9)
        pdf.cell(col_value, row_h, value, fill=True, align="R", ln=True)

    pdf.ln(4)


def _build_polar_table(pdf: _MirumPDF, polar: dict) -> None:
    """Page(s): full polar data table, paginated at 40 rows."""
    alpha_list = polar.get("alpha") or []
    Cl_list = polar.get("Cl") or []
    Cd_list = polar.get("Cd") or []
    Cm_list = polar.get("Cm") or []
    LD_list = polar.get("L_D") or []

    if not alpha_list:
        return

    # Zip, keeping only finite rows
    rows = []
    for a, cl, cd, cm, ld in zip(alpha_list, Cl_list, Cd_list, Cm_list, LD_list):
        rows.append((a, cl, cd, cm, ld))

    headers = ["α (°)", "Cl", "Cd", "Cm", "L/D"]
    col_widths = [
        _COL_W * 0.15,
        _COL_W * 0.18,
        _COL_W * 0.20,
        _COL_W * 0.18,
        _COL_W * 0.29,
    ]

    PAGE_ROWS = 40

    def _fmt(v) -> str:
        if v is None:
            return "—"
        try:
            f = float(v)
            return "—" if not math.isfinite(f) else f"{f:.5f}"
        except (TypeError, ValueError):
            return "—"

    for page_start in range(0, len(rows), PAGE_ROWS):
        pdf.add_page()
        # Dark background
        _set_fill(pdf, _DARK_BG)
        pdf.rect(0, 0, 210, 297, "F")

        pdf.set_y(_MARGIN)
        pdf.set_x(_MARGIN)
        pdf.set_font("Helvetica", "B", 11)
        _set_text(pdf, _ACCENT)
        naca = polar.get("naca_code", "?")
        pdf.cell(_COL_W, 7, f"Full Polar Table — NACA {naca}", ln=True)
        pdf.ln(2)

        # Header row
        _set_fill(pdf, _HEADER_BG)
        pdf.set_x(_MARGIN)
        pdf.set_font("Helvetica", "B", 8.5)
        _set_text(pdf, _TEXT_MAIN)
        for h, w in zip(headers, col_widths):
            pdf.cell(w, 7, h, fill=True, align="C", border=0)
        pdf.ln()

        # Data rows
        chunk = rows[page_start: page_start + PAGE_ROWS]
        for i, (a, cl, cd, cm, ld) in enumerate(chunk):
            fill = _ROW_ALT if i % 2 == 0 else _DARK_BG
            _set_fill(pdf, fill)
            pdf.set_x(_MARGIN)
            pdf.set_font("Helvetica", "", 8)
            _set_text(pdf, _TEXT_MAIN)
            vals = [
                f"{_safe_float(a):.2f}",
                _fmt(cl),
                _fmt(cd),
                _fmt(cm),
                _fmt(ld),
            ]
            for v, w in zip(vals, col_widths):
                pdf.cell(w, 6, v, fill=True, align="R", border=0)
            pdf.ln()


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def generate_xfoil_pdf(
    polar: dict,
    cl_alpha_b64: str,
    cd_alpha_b64: str,
    cp_dist_b64: Optional[str],
) -> bytes:
    """Generate an XFOIL aerodynamic report PDF.

    Parameters
    ----------
    polar : dict
        PolarReport.model_dump() — must contain at minimum naca_code,
        reynolds, mach, n_crit, chord_mm, alpha, Cl, Cd, Cm, L_D,
        converged_count; optionally stall_alpha, Cl_max.
    cl_alpha_b64 : str
        Base64-encoded PNG of the Cl vs α chart (from analysis/plots.py).
    cd_alpha_b64 : str
        Base64-encoded PNG of the Cd vs α chart.
    cp_dist_b64 : str or None
        Base64-encoded PNG of the Cp distribution, or None to skip.

    Returns
    -------
    bytes
        Raw PDF bytes. Stream directly to the client or write to disk.
    """
    summary = _compute_summary(polar)
    naca = polar.get("naca_code", "????")

    pdf = _MirumPDF(orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=14)
    pdf.set_margins(_MARGIN, _MARGIN, _MARGIN)

    # ── Page 1: Cover ────────────────────────────────────────
    _build_cover(pdf, polar)

    # ── Page 2: Summary + Cl-alpha chart ─────────────────────
    pdf.add_page()
    _set_fill(pdf, _DARK_BG)
    pdf.rect(0, 0, 210, 297, "F")
    pdf.set_y(_MARGIN)
    pdf.set_x(_MARGIN)
    _build_summary_table(pdf, summary)

    # Cl-alpha chart
    pdf.set_x(_MARGIN)
    pdf.set_font("Helvetica", "B", 10)
    _set_text(pdf, _ACCENT)
    pdf.cell(_COL_W, 6, f"Cl vs α — NACA {naca}", ln=True)
    pdf.ln(1)

    with tempfile.TemporaryDirectory() as tmpdir:
        _embed_png(pdf, cl_alpha_b64, tmpdir, "cl_alpha")

        # ── Page 3: Cd-alpha + Cp distribution ───────────────
        pdf.add_page()
        _set_fill(pdf, _DARK_BG)
        pdf.rect(0, 0, 210, 297, "F")
        pdf.set_y(_MARGIN)
        pdf.set_x(_MARGIN)

        pdf.set_font("Helvetica", "B", 10)
        _set_text(pdf, _ACCENT)
        pdf.cell(_COL_W, 6, f"Cd vs α — NACA {naca}", ln=True)
        pdf.ln(1)
        _embed_png(pdf, cd_alpha_b64, tmpdir, "cd_alpha")

        if cp_dist_b64:
            pdf.ln(4)
            pdf.set_x(_MARGIN)
            pdf.set_font("Helvetica", "B", 10)
            _set_text(pdf, _ACCENT)
            reynolds = _safe_float(polar.get("reynolds"))
            design_alpha = _safe_float(
                (polar.get("stall_alpha") or 0) * 0.6 or 4.0, 4.0
            )
            pdf.cell(
                _COL_W, 6,
                f"Cp Distribution — NACA {naca}  α={design_alpha:.1f}°  Re={reynolds/1e6:.2f}M",
                ln=True,
            )
            pdf.ln(1)
            _embed_png(pdf, cp_dist_b64, tmpdir, "cp_dist")

    # ── Pages 4+: Full polar data table ──────────────────────
    _build_polar_table(pdf, polar)

    return bytes(pdf.output())
