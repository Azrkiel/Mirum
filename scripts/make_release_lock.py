#!/usr/bin/env python3
"""Generate hashed pip locks for the release images.

Versions are never resolved here: every pin comes from an existing ``==`` lock.
For each pinned (name, version) this adds every file hash PyPI lists for that
exact version, so ``pip install --require-hashes --no-deps`` fails closed on
any gap.  TLS verification stays on (system trust store); no flags weaken it.

  python scripts/make_release_lock.py backend    # requirements-release.lock
  python scripts/make_release_lock.py frontend   # frontend/requirements.lock
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND_SOURCES = [
    "requirements-linux.lock",
    "requirements-mirum-verification.lock",
    "requirements-glider.lock",
]
# The existing locks are installed with plain pip in Dockerfile.verify, which silently pulls
# transitive packages they do not pin. --require-hashes --no-deps needs them explicit.
# Found by walking every pin's requires_dist (markers evaluated for the release image).
EXTRA_PINS = {"distro": "1.9.0"}  # google-genai 2.8.0 requires distro<2,>=1.7.0
FRONTEND_ROOTS = "frontend/requirements.txt"
ENV = {  # release image: python:3.10-slim-bookworm, linux/amd64
    "python_version": "3.10", "python_full_version": "3.10.22",
    "sys_platform": "linux", "platform_system": "Linux",
    "platform_machine": "x86_64", "os_name": "posix",
    "implementation_name": "cpython", "platform_python_implementation": "CPython",
    "platform_release": "", "platform_version": "", "implementation_version": "3.10.22",
}
PIN = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)\s*==\s*([^\s;#]+)")


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def read_pins(path: Path) -> dict[str, tuple[str, str]]:
    pins: dict[str, tuple[str, str]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = PIN.match(line)
        if m:
            pins[norm(m.group(1))] = (m.group(1), m.group(2))
    return pins


def fetch(name: str, version: str) -> dict:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=60) as r:  # default TLS verification
        return json.load(r)


def hashes_for(name: str, version: str) -> list[str]:
    files = fetch(name, version)["urls"]
    out = sorted({f["digests"]["sha256"] for f in files})
    if not out:
        raise SystemExit(f"no files on PyPI for {name}=={version}")
    return out


def render(pins: dict[str, tuple[str, str]], header: str) -> str:
    lines = [header]
    for key in sorted(pins):
        name, ver = pins[key]
        hs = hashes_for(name, ver)
        lines.append(f"{name}=={ver} \\")
        lines += [f"    --hash=sha256:{h} \\" for h in hs[:-1]]
        lines.append(f"    --hash=sha256:{hs[-1]}")
        print(f"{name}=={ver}: {len(hs)} hashes", file=sys.stderr)
    return "\n".join(lines) + "\n"


def backend() -> None:
    pins: dict[str, tuple[str, str]] = {}
    for src in BACKEND_SOURCES:
        for key, val in read_pins(ROOT / src).items():
            if key in pins and pins[key][1] != val[1]:
                raise SystemExit(f"version conflict for {key}: {pins[key]} vs {val}")
            pins[key] = val
    for name, ver in EXTRA_PINS.items():
        if norm(name) in pins:
            raise SystemExit(f"{name} is now pinned upstream; drop it from EXTRA_PINS")
        pins[norm(name)] = (name, ver)
    header = ("# Generated by scripts/make_release_lock.py from the == pins in\n"
              f"# {', '.join(BACKEND_SOURCES)} plus EXTRA_PINS. Do not edit by hand.\n"
              "# Install: pip install --require-hashes --no-deps -r requirements-release.lock")
    (ROOT / "requirements-release.lock").write_text(render(pins, header), encoding="utf-8", newline="\n")


def frontend() -> None:
    from packaging.requirements import Requirement  # lazy: generation-time only

    universe: dict[str, tuple[str, str]] = {}
    for src in BACKEND_SOURCES:  # same pins as the backend release lock
        universe.update(read_pins(ROOT / src))
    for key, val in read_pins(ROOT / FRONTEND_ROOTS).items():  # direct pins win (e.g. plotly)
        if key in universe and universe[key][1] != val[1]:
            raise SystemExit(f"version conflict for {key}: {universe[key]} vs {val}")
        universe[key] = val
    todo = [Requirement(l.split("#")[0].strip()).name
            for l in (ROOT / FRONTEND_ROOTS).read_text(encoding="utf-8").splitlines()
            if l.split("#")[0].strip()]
    chosen: dict[str, tuple[str, str]] = {}
    while todo:
        key = norm(todo.pop())
        if key in chosen:
            continue
        if key not in universe:
            raise SystemExit(f"{key} is not pinned in {BACKEND_SOURCES} or {FRONTEND_ROOTS}")
        chosen[key] = universe[key]
        name, ver = universe[key]
        for spec in fetch(name, ver)["info"].get("requires_dist") or []:
            req = Requirement(spec)
            if req.marker is None or req.marker.evaluate({**ENV, "extra": ""}):
                todo.append(req.name)
    header = ("# Generated by scripts/make_release_lock.py: the dependency closure of\n"
              f"# {FRONTEND_ROOTS}, versions taken from the backend == pins. Do not edit by hand.\n"
              "# Install: pip install --require-hashes --no-deps -r requirements.lock")
    (ROOT / "frontend/requirements.lock").write_text(render(chosen, header), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("target", choices=["backend", "frontend"])
    {"backend": backend, "frontend": frontend}[ap.parse_args().target]()
